const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const pw = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { setup } = require('./reports-workspace-harness.cjs');
const engine = process.env.BROWSER_ENGINE || 'chromium';
const out = process.env.QA_OUTPUT || '/tmp/carlab-fleet-batch-qa';
fs.mkdirSync(out, { recursive: true });
(async () => {
  const h = await setup(); let browser, page, phase = 'start';
  const errors = [];
  try {
    browser = await pw[engine].launch(engine === 'chromium' ? { channel: 'chrome', headless: true } : { headless: true });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const adminToken = h.token('admin');
    await context.addInitScript(token => localStorage.setItem('carlabToken', token), adminToken);
    page = await context.newPage(); page.setDefaultTimeout(15000);
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(h.url); await page.locator('#navFleetBtn').click();
    await page.waitForFunction(() => state.fleetUnits.length === 14 && !fleetLoadPromise);
    await page.locator('#fleetNewBtn').click(); await page.locator('#fleetModeBatchBtn').click();
    await page.locator('#fleetBatchEmpresa').fill('ANS'); await page.locator('#fleetBatchNombreFlota').fill('Lote verificado');
    await page.locator('#fleetBatchModelo').fill('i8'); await page.locator('#fleetBatchNumeros').fill('R001-R120');
    let requests = 0, resumeFirst;
    const firstGate = new Promise(resolve => { resumeFirst = resolve; });
    await page.route('**/api/fleet/units/batch', async route => {
      requests++;
      if (requests === 1) { await firstGate; return route.fulfill({ response: await route.fetch() }); }
      if (requests === 2) return route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ retryable: true, error: 'La base de datos no está disponible temporalmente.' }) });
      return route.continue();
    });
    phase = 'disable repeat submissions';
    await page.locator('#fleetBatchSaveBtn').click();
    await page.waitForFunction(() => state.fleetBatchSaving);
    assert.equal(await page.locator('#fleetBatchSaveBtn').isDisabled(), true);
    assert.equal(await page.locator('#fleetSaveBtn').isDisabled(), true);
    assert.equal(await page.locator('#fleetBatchEmpresa').isDisabled(), true);
    await page.evaluate(() => saveFleetBatch()); // Even a duplicate invocation must do nothing.
    assert.equal(requests, 1);
    await page.locator('#fleetBatchSummary').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(out, engine + '-progress.png'), fullPage: true });
    resumeFirst();
    await page.waitForFunction(() => !state.fleetBatchSaving);
    assert.equal(requests, 2, 'Stop at first failed block, do not submit block three');
    assert.equal((await page.locator('#fleetBatchNumeros').inputValue()).split('\n').length, 70);
    assert.equal((await page.locator('#fleetBatchNumeros').inputValue()).split('\n')[0], 'R051');
    assert.match(await page.locator('#fleetBatchSummary').innerText(), /50 de 120/);
    assert.equal(await page.evaluate(() => state.fleetDirty), true);
    assert.equal((await h.db.query("SELECT COUNT(*)::int AS total FROM fleet_units WHERE numero_economico LIKE 'R%'")).rows[0].total, 50);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#fleetBatchSummary').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(out, engine + '-pending-mobile.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
    phase = 'resume only pending units';
    await page.unroute('**/api/fleet/units/batch');
    await page.locator('#fleetBatchSaveBtn').click();
    await page.waitForFunction(() => !state.fleetBatchSaving && !state.fleetDirty);
    assert.equal(await page.locator('#fleetBatchNumeros').inputValue(), '');
    assert.match(await page.locator('#fleetBatchSummary').innerText(), /70 unidades nuevas/);
    assert.equal((await h.db.query("SELECT COUNT(*)::int AS total FROM fleet_units WHERE numero_economico LIKE 'R%'")).rows[0].total, 120);
    assert.equal(await page.locator('#fleetBatchEmpresa').inputValue(), 'ANS');
    phase = 'lost acknowledgement';
    await page.locator('#fleetBatchNumeros').fill('LOST001, LOST002');
    await page.route('**/api/fleet/units/batch', async route => { await route.fetch(); await route.abort('failed'); });
    await page.locator('#fleetBatchSaveBtn').click(); await page.waitForFunction(() => !state.fleetBatchSaving);
    assert.equal(await page.locator('#fleetBatchNumeros').inputValue(), 'LOST001\nLOST002');
    await page.unroute('**/api/fleet/units/batch');
    await page.locator('#fleetBatchModelo').fill('Must not replace');
    await page.locator('#fleetBatchSaveBtn').click(); await page.waitForFunction(() => !state.fleetBatchSaving && !state.fleetDirty);
    assert.match(await page.locator('#fleetBatchSummary').innerText(), /0 unidades nuevas y 2 existentes/);
    assert.deepEqual((await h.db.query("SELECT modelo FROM fleet_units WHERE numero_economico LIKE 'LOST%'")).rows.map(row => row.modelo), ['i8', 'i8']);
    phase = 'range validation';
    await page.locator('#fleetBatchNumeros').fill('1-501'); await page.locator('#fleetBatchSaveBtn').click();
    assert.equal(await page.locator('#fleetBatchNumeros').inputValue(), '1-501');
    assert.equal(await page.evaluate(() => state.fleetBatchSaving), false);
    assert.match(await page.locator('#toast').innerText(), /500/);
    await page.locator('#fleetBatchNumeros').fill('321'); await page.locator('#fleetBatchSaveBtn').click();
    await page.waitForFunction(() => !state.fleetBatchSaving && !state.fleetDirty);
    await page.locator('#fleetBatchSummary').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(out, engine + '-complete-mobile.png'), fullPage: true });
    phase = 'session preserved on database outage';
    await page.route('**/api/auth/me', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Base no disponible', retryable: true }) }));
    await page.reload(); await page.waitForFunction(() => document.querySelector('#toast')?.textContent.includes('Tu sesión se conserva'));
    assert.equal(await page.evaluate(() => localStorage.getItem('carlabToken')), adminToken);
    await page.unroute('**/api/auth/me');
    await page.route('**/api/auth/me', route => route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ error: 'Sesión inválida' }) }));
    await page.reload(); await page.waitForFunction(() => !localStorage.getItem('carlabToken'));
    assert.deepEqual(errors, []);
    console.log('PASS ' + engine + ': progress, duplicate submit, outage stops at block 2/3, 70 pending retained, safe replay, mobile, range validation, session preservation.');
  } catch (error) { console.error('Phase:', phase); if (page) await page.screenshot({ path: path.join(out, engine + '-failure.png'), fullPage: true }).catch(() => {}); throw error; }
  finally { if (browser) await browser.close(); await h.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
